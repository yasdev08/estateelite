export function getPropertyById(id: string): Property | undefined {
  return PROPERTIES.find((p) => p.id === id);
}

export function getPropertyBySlug(slug: string): Property | undefined {
  return PROPERTIES.find((p) => p.slug === slug);
}

export function getFeaturedProperties(limit = 6): Property[] {
  return PROPERTIES.filter((p) => p.featured).slice(0, limit);
}

export function getRelatedProperties(id: string, limit = 3): Property[] {
  const prop = getPropertyById(id);
  if (!prop) return [];
  return PROPERTIES.filter(
    (p) => p.id !== id && (p.type === prop.type || p.city === prop.city)
  ).slice(0, limit);
}
